#!/usr/bin/env python3
"""Builds site/map.svg and site/countries.js for images/world-quiz.

usage:
  python3 -I tools/build_map.py <ne_50m_admin_0_countries.geojson> [--out DIR] [--check]

Offline, stdlib only (Python 3.9+), deterministic: the same inputs give
byte-identical outputs. --check builds in memory and exits 1 if the files in
the output folder differ (nothing is written). Details: tools/README.md.

This file is world-quiz's adapter: Natural Earth, the border view, the quiz
set, the small-state rule, far-flung parts and the rings. The geometry
(Buckminster Fuller's Dymaxion (Airocean) projection, clipping per net
piece, shared borders, simplification, SVG) is the shared map-quiz core,
shared/map-quiz/tools/mapgen (mapgen.Polyhedral for the projection).

Pipeline:
  1. Natural Earth admin-0 countries, 50m, v5.1.2 (sha256-verified).
  2. Border view (EU/Austrian official view where it differs from Natural
     Earth's de-facto layer; tools/README.md): Crimea -> Ukraine; Northern
     Cyprus, Somaliland, Aland, Hong Kong and Macao merge into Cyprus,
     Somalia, Finland and China; the Golan Heights -> Syria and Western
     Sahara out of Morocco (context land) cut along lon/lat lines (CUTS),
     Ceuta and Melilla -> Spain clipped by small boxes (BOXES). The cuts'
     new vertices go into the neighbours too; no T-junction anywhere
     (asserted, also after the antimeridian stitch). Point checks
     (VIEW_CHECKS) assert the result; EMPTY that tiny disputed islands are
     not in the file at this scale.
  3. Quiz states (tools/countries.json, 197) are regions; every other
     feature (CONTEXT: dependencies and territories, Palestine, Western
     Sahara, the Siachen Glacier, Antarctica) is one merged context path.
     The small-state flags and the rings are checked against their rules
     (SMALL_*, RING_SIZE) on the map as drawn (step 6).
  4. Natural Earth cuts land at 180 degrees: stitched so the halves merge.
  5. Projection: Fuller's icosahedron and net in Gray's exact transform
     (mapgen.Polyhedral("fuller")); each polygon is clipped per net piece
     on the sphere. Parts of a quiz state cut off by the net, far from its
     main polygon and tiny (FAR_*: the Chatham Islands and Tokelau of New
     Zealand, a Fiji islet) are dropped, and the list is asserted.
  6. (mapgen) Window = the net plus MARGIN; snap to 1/GRID, merge parts,
     drop tiny unshared islands (never for ringed states), shared arcs,
     Douglas-Peucker on the arcs (REGION_TOL; RING_TOL for ringed states;
     CONTEXT_TOL), arcs in a crossing restored until there is none.
  7. map.svg: the net's shape (<path id="net">, the sea) and its folds
     (<path id="folds">) first, then context land, the 197 states; and
     countries.js (names, capitals, flags, projected marker points, sizes).
"""

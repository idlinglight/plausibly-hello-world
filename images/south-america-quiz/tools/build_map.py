#!/usr/bin/env python3
"""Builds site/map.svg and site/countries.js for images/south-america-quiz.

usage:
  python3 -I tools/build_map.py <ne_50m_admin_0_countries.geojson> [--out DIR] [--check]

Offline, stdlib only (Python 3.9+), deterministic: the same inputs give
byte-identical outputs. --check builds in memory and exits 1 if the files in
the output folder differ (nothing is written). Details: tools/README.md.

This file is south-america-quiz's adapter: Natural Earth, French Guiana,
the border view, remote parts, the window and the quiz set. The geometry
(projection, clipping, shared borders, simplification, SVG) is the shared
map-quiz core, shared/map-quiz/tools/mapgen.

Pipeline:
  1. Natural Earth admin-0 countries, 50m, v5.1.2 (sha256-verified; the
     file europe-quiz pins).
  2. French Guiana: Natural Earth draws it as a polygon of France (FRA);
     the polygon containing Cayenne becomes its own feature, GUF.
  3. Border view: Natural Earth's default layer as it is (de-facto
     administration): Essequibo and the New River Triangle in Guyana, the
     Litani-Marouini area in French Guiana, the Falkland Islands their own
     feature, the Southern Patagonian Ice Field line as drawn. Point checks
     (VIEW_CHECKS) assert it.
  4. Quiz set (tools/countries.json, entries without "quiz": false) stay
     separate; every other feature (the Falkland Islands too) becomes one
     merged context-land path.
  5. Window (the full view): the bounding box of all quiz geometry except
     remote parts (REMOTE below: the Galápagos, Easter Island), plus a
     margin; asserts that all other quiz geometry lies inside it. Around
     it, EXTENT more context is drawn (wide screens show map, not blank)
     and clipped; only remote parts may be clipped there. The Galápagos lie
     inside the extent: drawn at their real position as part of Ecuador.
  6. Projection: Lambert azimuthal equal-area centred on 20°S 60°W (GRS80),
     scaled to a WIDTH-unit-wide viewBox, y down.
  7. (mapgen) Clip to the extent, snap to a 1/GRID grid, merge parts (cancel
     shared segments), drop tiny unshared islands, then build shared arcs so
     neighbours use identical border vertices (no gaps or overlaps).
     Context-only arcs get a light Douglas-Peucker (a stronger one outside
     the window, where context is only seen small); quiz arcs keep every
     vertex.
  8. Write map.svg (one <path> per quiz entry, relative commands, no
     styling) and countries.js (names, capitals, projected marker points).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(REPO, "shared", "map-quiz", "tools"))
import mapgen  # noqa: E402  (shared core; python3 -I keeps the script's folder off sys.path)

# ------------------------------------------------------------------ input
NE_FILE = "ne_50m_admin_0_countries.geojson"
NE_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/" + NE_FILE
NE_SHA256 = "3e458fc036ad0a66411f2c1e6cac49c5d7bfb81cb1123bc513b22511a2b7fdeb"
NE_BYTES = 3083490

COUNTRIES_JSON = os.path.join(HERE, "countries.json")

# ------------------------------------------------------------------ output
LAT0, LON0 = -20.0, -60.0  # projection centre: the middle of the continent
WIDTH = 1000.0      # viewBox width in map units
GRID = 10           # vertices snap to 1/GRID unit (0.1)
MARGIN = 0.03       # window margin around the quiz geometry, fraction of its width
EXTENT = (0.60, 0.20)  # context drawn around the window: fraction of its width / height per side
MIN_ISLAND = 0.3    # drop islands below this area (units^2) unless they touch another ring
CONTEXT_TOL = 0.2   # Douglas-Peucker tolerance (units) for arcs only context land uses …
FAR_TOL = 1.5       # … and for their runs of points outside the window (+ FAR_GAP): only seen small
FAR_MIN_ISLAND = 4  # context islands entirely outside the window: dropped below this (units^2)
FAR_GAP = 20        # units around the window that still count as near

HEAD = ("Generated by tools/build_map.py from tools/countries.json and Natural Earth v5.1.2 (public domain). "
        "Don't edit: change the inputs and regenerate.")

# ------------------------------------------------------------------ French Guiana, border view
# (source feature, new feature, a point inside the polygon that moves, label)
SPLITS = [("FRA", "GUF", (-52.33, 4.94), "French Guiana")]
# (lon, lat, expected owner after the split, label)
VIEW_CHECKS = [
    (-58.62, 6.40, "GUY", "Bartica (Essequibo)"),
    (-59.80, 3.38, "GUY", "Lethem (Essequibo)"),
    (-61.11, 4.60, "VEN", "Santa Elena de Uairén (Venezuela, west of Essequibo)"),
    (-57.40, 2.30, "GUY", "New River Triangle"),
    (-54.30, 2.60, "GUF", "Litani-Marouini area"),
    (-52.33, 4.94, "GUF", "Cayenne"),
    (-55.20, 5.85, "SUR", "Paramaribo"),
    (-72.89, -49.33, "ARG", "El Chaltén (Southern Patagonian Ice Field, east)"),
    (-73.57, -47.80, "CHL", "Caleta Tortel (Southern Patagonian Ice Field, north-west)"),
    (-72.51, -51.73, "CHL", "Puerto Natales"),
    (-57.85, -51.69, "FLK", "Stanley (Falkland Islands)"),
    (-36.50, -54.30, "SGS", "South Georgia (context land)"),
    (-61.25, 10.45, "TTO", "Trinidad (context land)"),
    (-90.35, -0.75, "ECU", "Santa Cruz (Galápagos)"),
]

# Remote parts of quiz entries: polygons whose bounding box lies entirely
# inside one of these lon/lat boxes don't count for the window and may be
# clipped. Every rule must match at least one polygon.
REMOTE = [
    ("ECU", "Galápagos", (-92.5, -88.5), (-2, 1)),
    ("CHL", "Easter Island", (-110, -108), (-28, -26)),
]
PREFILTER = ((-180, 60), (-90, 45))  # lon/lat box: polygons entirely outside are skipped early


def fail(msg):
    raise mapgen.BuildError(msg)


# ------------------------------------------------------------------ steps
def load_ne(path):
    raw = mapgen.read_pinned(path, NE_SHA256, NE_BYTES, NE_URL)
    geo = {}
    for f in json.loads(raw.decode("utf-8"))["features"]:
        geo.setdefault(f["properties"]["ADM0_A3"], []).extend(mapgen.polys_of(f["geometry"]))
    return geo


def load_countries():
    with open(COUNTRIES_JSON, encoding="utf-8") as fh:
        cl = json.load(fh)["countries"]
    ids = [c["id"] for c in cl]
    if len(set(ids)) != len(ids):
        fail("countries.json: duplicate ids")
    for key in ("name", "capital"):
        vals = [c[key] for c in cl]
        if any(not isinstance(v, str) or not v or v != v.strip() for v in vals):
            fail(f"countries.json: empty or padded {key}")
        if len(set(vals)) != len(vals):
            fail(f"countries.json: duplicate {key}")
    for c in cl:
        if not isinstance(c.get("quiz", True), bool):
            fail(f"countries.json: quiz must be true or false ({c['id']})")
        of = c.get("of")
        if of is not None and (not isinstance(of, str) or not of or of != of.strip()):
            fail(f"countries.json: empty or padded of ({c['id']})")
        m = c.get("marker")
        if m is not None and not (len(m) == 2 and -180 <= m[0] <= 180 and -90 <= m[1] <= 90):
            fail(f"countries.json: bad marker for {c['id']}")
    return cl


def apply_splits(geo, notes):
    for src, new, (lon, lat), label in SPLITS:
        if src not in geo or new in geo:
            fail(f"split {src} -> {new}: {src} missing or {new} already there")
        hit = [p for p in geo[src] if mapgen.in_polygon(lon, lat, p)]
        if len(hit) != 1:
            fail(f"split {label}: expected one {src} polygon at ({lon}, {lat}), found {len(hit)}")
        geo[src] = [p for p in geo[src] if p is not hit[0]]
        geo[new] = hit
        notes.append(f"{label}: {src} polygon -> {new}")


def check_view(geo, notes):
    for lon, lat, want, label in VIEW_CHECKS:
        got = mapgen.owner_of(geo, lon, lat)
        if got != want:
            fail(f"border view check: {label} ({lon}, {lat}) is in {got}, expected {want}")
    notes.append(f"{len(VIEW_CHECKS)} border-view point checks passed")


def is_remote(a3, poly):
    x0, y0, x1, y1 = mapgen.bbox(poly[0])
    for i, (rid, _, (lo0, lo1), (la0, la1)) in enumerate(REMOTE):
        if rid == a3 and lo0 <= x0 and x1 <= lo1 and la0 <= y0 and y1 <= la1:
            return i
    return None


def prefiltered(poly):
    x0, y0, x1, y1 = mapgen.bbox(poly[0])
    (lo0, lo1), (la0, la1) = PREFILTER
    return x1 >= lo0 and x0 <= lo1 and y1 >= la0 and y0 <= la1


def build(ne_path):
    notes = []
    project = mapgen.LambertAzimuthalEqualArea(LAT0, LON0, ellipsoid=mapgen.GRS80,
                                               name=f"LAEA {-LAT0:g}S {-LON0:g}W")
    x, y = project(LON0, LAT0)
    if abs(x) > 1e-6 or abs(y) > 1e-6:
        fail("projection: centre doesn't map to 0, 0")
    mapgen.epsg3035().self_test()  # the same LAEA formulas against EPSG's reference point
    entries = load_countries()
    countries = [c for c in entries if c.get("quiz", True)]
    quiz = [c["id"] for c in countries]
    geo = load_ne(ne_path)
    apply_splits(geo, notes)
    for c in entries:
        if c["id"] not in geo:
            fail(f"{c['id']} not in {NE_FILE} (nor split out of it)")
    check_view(geo, notes)
    notes.append("context land from countries.json: " + (", ".join(c["id"] for c in entries if c not in countries)
                                                        or "none"))

    # Window: quiz geometry minus remote parts, plus a margin.
    remote_hits = [0] * len(REMOTE)
    core_pts = []
    for a3 in quiz:
        main = max(geo[a3], key=lambda p: abs(mapgen.area2(p[0])))
        if is_remote(a3, main) is not None:
            fail(f"{a3}: its largest polygon matches a REMOTE rule")
        for p in geo[a3]:
            r = is_remote(a3, p)
            if r is None:
                core_pts.extend(project(c[0], c[1]) for c in p[0])
            else:
                remote_hits[r] += 1
    for (rid, label, _, _), n in zip(REMOTE, remote_hits):
        if not n:
            fail(f"REMOTE rule {rid} '{label}' matches nothing")
    window = mapgen.Window(core_pts, MARGIN, WIDTH, EXTENT)

    # Quiz entries are regions (remote parts may be clipped), everything
    # else context land; in Natural Earth's order, split features last (the
    # output depends on it).
    mb = mapgen.MapBuilder(project, window, quiz, grid=GRID, min_island=MIN_ISLAND, context_tol=CONTEXT_TOL,
                           far_tol=FAR_TOL, far_min_island=FAR_MIN_ISLAND, far_gap=FAR_GAP)
    for a3, polys in geo.items():
        for p in polys:
            if not prefiltered(p):
                continue
            if a3 in quiz:
                r = is_remote(a3, p)
                mb.add_region(a3, p, outside_ok=r is not None, label=None if r is None else f"{a3} {REMOTE[r][1]}")
            else:
                mb.add_context(p)
    # Markered entries keep every island.
    res = mb.build(keep_islands={c["id"] for c in countries if c.get("marker")})
    markers = {c["id"]: mb.point(*c["marker"], f"{c['id']}: marker") for c in countries if c.get("marker")}

    def r1(v):
        return round(v, 1)

    svg_text = mapgen.map_svg(res, quiz, HEAD, group_id="countries")
    js = [
        f"// {HEAD}",
        "//",
        "// MAP: the window (full view) is 0 0 width height in map units; extent",
        "// [x, y, w, h] is map.svg's viewBox, the context drawn around it.",
        "// COUNTRIES: the quiz set in countries.json order (entries with quiz: false",
        "// are context land, not here); of: the state a territory belongs to;",
        "// marker: [x, y] in map units, size: the larger side of the entry's",
        "// bounding box (map units), for markered entries only.",
        "",
        window.map_js(),
        "",
        "export const COUNTRIES = [",
    ]
    for c in countries:
        parts = [f"id: {mapgen.js_string(c['id'])}", f"name: {mapgen.js_string(c['name'])}",
                 f"capital: {mapgen.js_string(c['capital'])}"]
        if c.get("of"):
            parts.append(f"of: {mapgen.js_string(c['of'])}")
        if c["id"] in markers:
            mx, my = markers[c["id"]]
            parts.append(f"marker: [{r1(mx):g}, {r1(my):g}]")
            parts.append(f"size: {r1(res.sizes[c['id']]):g}")
        js.append("  { " + ", ".join(parts) + " },")
    js += ["];", ""]
    return {"map.svg": svg_text, "countries.js": "\n".join(js)}, res.report(quiz, notes)


def main():
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("ne", help=f"path to {NE_FILE} (Natural Earth v5.1.2)")
    ap.add_argument("--out", default=os.path.join(HERE, "..", "site"), help="output folder (default: ../site)")
    ap.add_argument("--check", action="store_true", help="compare with the files in --out instead of writing")
    args = ap.parse_args()
    try:
        files, report = build(args.ne)
    except (mapgen.BuildError, ValueError) as e:
        sys.exit(f"build_map: {e}")
    sys.exit(mapgen.emit(files, args.out, args.check, report))


if __name__ == "__main__":
    main()
